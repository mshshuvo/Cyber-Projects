"""Coverage statistics and report rendering (console, Markdown, JSON)."""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from datetime import date

from .catalog import ANNEX_A, THEMES, theme_of
from .checks import HIGH, LOW, MEDIUM, Finding, readiness_score
from .models import IMPLEMENTED, PARTIAL, SoAEntry


def coverage_by_theme(soa: list[SoAEntry]) -> dict[str, dict[str, int]]:
    """Count applicable / implemented / partial / excluded controls per theme."""
    seen: set[str] = set()
    stats: dict[str, dict[str, int]] = defaultdict(
        lambda: {"in_catalog": 0, "applicable": 0, "implemented": 0, "partial": 0, "excluded": 0})
    for cid in ANNEX_A:
        stats[theme_of(cid)]["in_catalog"] += 1
    for e in soa:
        if e.control_id not in ANNEX_A or e.control_id in seen:
            continue
        seen.add(e.control_id)
        s = stats[theme_of(e.control_id)]
        if not e.applicable:
            s["excluded"] += 1
            continue
        s["applicable"] += 1
        if e.status == IMPLEMENTED:
            s["implemented"] += 1
        elif e.status == PARTIAL:
            s["partial"] += 1
    return {t: dict(stats[t]) for t in THEMES.values()}


def _pct(part: int, whole: int) -> str:
    return f"{(100 * part / whole):.0f}%" if whole else "n/a"


def _bar(part: int, whole: int, width: int = 20) -> str:
    filled = round(width * part / whole) if whole else 0
    return "█" * filled + "░" * (width - filled)


def console_summary(soa: list[SoAEntry], findings: list[Finding], as_of: date) -> str:
    cov = coverage_by_theme(soa)
    sev = Counter(f.severity for f in findings)
    lines = [
        f"ISO/IEC 27001:2022 SoA audit  (as of {as_of})",
        "=" * 56,
        f"Readiness score: {readiness_score(findings)}/100   "
        f"Findings: {len(findings)}  (High {sev[HIGH]}, Medium {sev[MEDIUM]}, Low {sev[LOW]})",
        "",
        "Implementation coverage of applicable controls:",
    ]
    for theme, s in cov.items():
        lines.append(f"  {theme:<14} {_bar(s['implemented'], s['applicable'])} "
                     f"{_pct(s['implemented'], s['applicable']):>4}  "
                     f"({s['implemented']}/{s['applicable']} implemented, "
                     f"{s['partial']} partial, {s['excluded']} excluded)")
    lines += ["", "Top findings:"]
    for f in findings[:10]:
        lines.append(f"  [{f.severity:<6}] {f.ref:<8} {f.check:<28} {f.message}")
    if len(findings) > 10:
        lines.append(f"  ... and {len(findings) - 10} more in the full report.")
    return "\n".join(lines)


def markdown_report(soa: list[SoAEntry], findings: list[Finding], as_of: date,
                    org: str) -> str:
    cov = coverage_by_theme(soa)
    sev = Counter(f.severity for f in findings)
    by_check = Counter(f.check for f in findings)
    md = [
        f"# SoA Audit Report — {org}",
        "",
        f"*Standard:* ISO/IEC 27001:2022 · *As of:* {as_of} · "
        f"*Readiness score:* **{readiness_score(findings)}/100**",
        "",
        "## Summary",
        "",
        "| Severity | Count |", "|---|---|",
        f"| High | {sev[HIGH]} |", f"| Medium | {sev[MEDIUM]} |", f"| Low | {sev[LOW]} |",
        "",
        "## Coverage by theme",
        "",
        "| Theme | Annex A | Applicable | Implemented | Partial | Excluded | Implemented % |",
        "|---|---|---|---|---|---|---|",
    ]
    for theme, s in cov.items():
        md.append(f"| {theme} | {s['in_catalog']} | {s['applicable']} | {s['implemented']} | "
                  f"{s['partial']} | {s['excluded']} | {_pct(s['implemented'], s['applicable'])} |")
    md += ["", "## Findings by type", "", "| Check | Count |", "|---|---|"]
    md += [f"| {c} | {n} |" for c, n in by_check.most_common()]
    md += ["", "## Detailed findings", "",
           "| # | Severity | Reference | Clause | Check | Detail |", "|---|---|---|---|---|---|"]
    for i, f in enumerate(findings, 1):
        md.append(f"| {i} | {f.severity} | {f.ref} | {f.clause} | {f.check} | "
                  f"{f.message.replace('|', '/')} |")
    md += ["", "---", "*Generated by soa_auditor. Findings are indicators for auditor "
           "judgement, not a certification decision.*", ""]
    return "\n".join(md)


def json_report(soa: list[SoAEntry], findings: list[Finding], as_of: date, org: str) -> str:
    return json.dumps({
        "organization": org,
        "as_of": as_of.isoformat(),
        "readiness_score": readiness_score(findings),
        "coverage": coverage_by_theme(soa),
        "findings": [f.to_dict() for f in findings],
    }, indent=2)
